#!/usr/bin/env python3
"""Compute disease-wise AUROC/AUPRC on the official NIH ChestX-ray14 Test set.

This script evaluates already-saved Platt-calibrated probabilities. It does not
fit calibration parameters or select thresholds. Frozen OOF thresholds from the
operating-point analysis are joined only for comparison.

Expected project files:
  reports/test_evaluation/test_predictions_public.csv.gz
  reports/operating_points/test_operating_points.csv

Outputs:
  reports/disease_level_analysis/test_disease_ranking_metrics.csv
  reports/disease_level_analysis/test_disease_ranking_operating_points.csv
  reports/disease_level_analysis/test_disease_ranking_summary.csv
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

try:
    from .constants import DISEASES
except ImportError:  # Support running scripts as: python src/<script>.py
    from constants import DISEASES
MODELS = ["densenet121", "efficientnet_b0", "soft_voting_ensemble"]
CRITERIA = ["YoudenJ", "Sensitivity90", "Specificity90"]
IMAGE_COL = "Image Index"
PATIENT_COL = "Patient ID"


def parse_args() -> argparse.Namespace:
    project_dir = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(
        description="Calculate disease-wise Test AUROC/AUPRC and join frozen operating points."
    )
    parser.add_argument(
        "--predictions",
        type=Path,
        default=project_dir / "reports/test_evaluation/test_predictions_public.csv.gz",
        help="Compact official Test predictions CSV (gzip-compressed).",
    )
    parser.add_argument(
        "--operating-points",
        type=Path,
        default=project_dir / "reports/operating_points/test_operating_points.csv",
        help="Test operating-point metrics using thresholds frozen from OOF.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=project_dir / "reports/disease_level_analysis",
        help="Directory for output CSV files.",
    )
    return parser.parse_args()


def require_columns(df: pd.DataFrame, required: set[str], source: Path) -> None:
    missing = sorted(required - set(df.columns))
    if missing:
        raise KeyError(f"Missing columns in {source}: {missing}")


def validate_binary_labels(df: pd.DataFrame) -> None:
    for disease in DISEASES:
        values = pd.to_numeric(df[disease], errors="raise")
        unique = set(values.dropna().unique().tolist())
        if values.isna().any() or not unique.issubset({0, 1}):
            raise ValueError(
                f"Label column {disease} must contain only non-missing 0/1 values; got {unique}"
            )
        if len(unique) != 2:
            raise ValueError(
                f"Test label {disease} must contain both positive and negative examples; got {unique}"
            )
        df[disease] = values.astype(np.uint8)


def main() -> int:
    args = parse_args()
    predictions_path = args.predictions.resolve()
    op_path = args.operating_points.resolve()
    output_dir = args.output_dir.resolve()

    # Prefer the compact public artifact; fall back to full local predictions
    # generated by evaluate_test.py when the public file is not present.
    default_predictions = (Path(__file__).resolve().parents[1]
                           / "reports/test_evaluation/test_predictions_public.csv.gz")
    if not predictions_path.is_file() and predictions_path == default_predictions:
        legacy_predictions = default_predictions.with_name("test_predictions.csv")
        if legacy_predictions.is_file():
            predictions_path = legacy_predictions

    print("=" * 76)
    print("CXR14 DISEASE-WISE TEST AUROC / AUPRC ANALYSIS")
    print("=" * 76)
    print(f"Predictions:     {predictions_path}")
    print(f"Operating point: {op_path}")

    if not predictions_path.exists():
        raise FileNotFoundError(f"Test predictions file not found: {predictions_path}")
    if not op_path.exists():
        raise FileNotFoundError(f"Operating-point file not found: {op_path}")

    # Load official Test labels and predictions for final evaluation only.
    predictions = pd.read_csv(
        predictions_path,
        dtype={IMAGE_COL: "string", PATIENT_COL: "string"},
    )
    require_columns(
        predictions,
        {IMAGE_COL, PATIENT_COL, *DISEASES}
        | {
            f"{model}_platt_{disease}"
            for model in MODELS
            for disease in DISEASES
        },
        predictions_path,
    )
    if predictions[IMAGE_COL].isna().any() or predictions[IMAGE_COL].duplicated().any():
        raise ValueError("Test predictions contain missing or duplicated Image Index values.")
    if predictions[PATIENT_COL].isna().any():
        raise ValueError("Test predictions contain missing Patient ID values.")
    if len(predictions) != 25_596:
        raise ValueError(
            f"Expected 25,596 official Test images, found {len(predictions):,}. "
            "Check that the supplied predictions file is the official NIH Test output."
        )
    n_patients = int(predictions[PATIENT_COL].nunique())
    if n_patients != 2_797:
        print(
            f"[WARN] Expected 2,797 Test patients based on the project split, "
            f"found {n_patients:,}. Continuing with the supplied file."
        )

    validate_binary_labels(predictions)

    op_df = pd.read_csv(op_path)
    required_op_cols = {
        "Model", "Disease", "Criterion", "Threshold_From_OOF",
        "Test_Sensitivity", "Test_Specificity", "Test_PPV", "Test_NPV",
        "Test_F1", "Test_YoudenJ", "TP", "FP", "TN", "FN",
    }
    require_columns(op_df, required_op_cols, op_path)
    op_df = op_df[
        op_df["Model"].isin(MODELS)
        & op_df["Disease"].isin(DISEASES)
        & op_df["Criterion"].isin(CRITERIA)
    ].copy()
    if op_df.duplicated(["Model", "Disease", "Criterion"]).any():
        raise ValueError("Operating-point CSV contains duplicate Model/Disease/Criterion rows.")
    expected_op_rows = len(MODELS) * len(DISEASES) * len(CRITERIA)
    if len(op_df) != expected_op_rows:
        raise ValueError(
            f"Expected {expected_op_rows} operating-point rows, found {len(op_df)}."
        )

    ranking_rows: list[dict] = []
    prevalence_rows: list[dict] = []
    for disease in DISEASES:
        y_true = predictions[disease].to_numpy(dtype=np.uint8)
        positives = int(y_true.sum())
        negatives = int(len(y_true) - positives)
        prevalence = positives / len(y_true)
        prevalence_rows.append({
            "Disease": disease,
            "Test_Images": int(len(y_true)),
            "Test_Positive_Count": positives,
            "Test_Negative_Count": negatives,
            "Test_Prevalence": prevalence,
        })

        for model in MODELS:
            column = f"{model}_platt_{disease}"
            scores = pd.to_numeric(predictions[column], errors="raise").to_numpy(dtype=float)
            if not np.isfinite(scores).all():
                raise ValueError(f"Non-finite probability values in {column}.")
            if np.any(scores < 0.0) or np.any(scores > 1.0):
                raise ValueError(f"Probabilities in {column} must be within [0, 1].")
            if np.unique(scores).size < 2:
                raise ValueError(f"All probabilities are identical in {column}.")

            auc = float(roc_auc_score(y_true, scores))
            # Average Precision is used as the project's PR-AUC/AUPRC convention.
            ap = float(average_precision_score(y_true, scores))
            ranking_rows.append({
                "Model": model,
                "Disease": disease,
                "Test_Images": int(len(y_true)),
                "Test_Positive_Count": positives,
                "Test_Negative_Count": negatives,
                "Test_Prevalence": prevalence,
                "AUROC": auc,
                "AUPRC_AveragePrecision": ap,
                "Prevalence_AP_Baseline": prevalence,
                "AUROC_Rank_Within_Model": np.nan,
                "AUPRC_Rank_Within_Model": np.nan,
            })

    ranking_df = pd.DataFrame(ranking_rows)
    ranking_df["AUROC_Rank_Within_Model"] = ranking_df.groupby("Model")["AUROC"].rank(
        ascending=False, method="min"
    ).astype(int)
    ranking_df["AUPRC_Rank_Within_Model"] = ranking_df.groupby("Model")[
        "AUPRC_AveragePrecision"
    ].rank(ascending=False, method="min").astype(int)

    summary_df = (
        ranking_df.groupby("Model", sort=False)
        .agg(
            Diseases=("Disease", "nunique"),
            Macro_AUROC=("AUROC", "mean"),
            Std_AUROC_Across_Diseases=("AUROC", "std"),
            Macro_AUPRC=("AUPRC_AveragePrecision", "mean"),
            Std_AUPRC_Across_Diseases=("AUPRC_AveragePrecision", "std"),
        )
        .reset_index()
    )

    op_metrics = op_df.rename(columns={
        "Threshold_From_OOF": "OOF_Frozen_Threshold",
        "Test_Sensitivity": "OperatingPoint_Test_Sensitivity",
        "Test_Specificity": "OperatingPoint_Test_Specificity",
        "Test_PPV": "OperatingPoint_Test_PPV",
        "Test_NPV": "OperatingPoint_Test_NPV",
        "Test_F1": "OperatingPoint_Test_F1",
        "Test_YoudenJ": "OperatingPoint_Test_YoudenJ",
    })
    comparison_df = op_metrics.merge(
        ranking_df,
        on=["Model", "Disease"],
        how="left",
        validate="many_to_one",
    )
    if comparison_df[["AUROC", "AUPRC_AveragePrecision"]].isna().any().any():
        raise AssertionError("Some operating-point rows failed to match ranking metrics.")

    output_dir.mkdir(parents=True, exist_ok=True)
    ranking_path = output_dir / "test_disease_ranking_metrics.csv"
    comparison_path = output_dir / "test_disease_ranking_operating_points.csv"
    summary_path = output_dir / "test_disease_ranking_summary.csv"
    prevalence_path = output_dir / "test_disease_prevalence.csv"

    ranking_df.to_csv(ranking_path, index=False, float_format="%.8f")
    comparison_df.to_csv(comparison_path, index=False, float_format="%.8f")
    summary_df.to_csv(summary_path, index=False, float_format="%.8f")
    pd.DataFrame(prevalence_rows).to_csv(prevalence_path, index=False, float_format="%.8f")

    print("\nTest cohort:")
    print(f"  Images:   {len(predictions):,}")
    print(f"  Patients: {n_patients:,}")
    print("\nMacro ranking metrics (14-disease macro average):")
    print(summary_df.to_string(index=False, float_format=lambda x: f"{x:.4f}"))
    print("\nTop / bottom Ensemble diseases:")
    ensemble = ranking_df[ranking_df["Model"] == "soft_voting_ensemble"].copy()
    print("  Highest AUROC:")
    print(
        ensemble.nlargest(3, "AUROC")[["Disease", "AUROC", "AUPRC_AveragePrecision"]]
        .to_string(index=False, float_format=lambda x: f"{x:.4f}")
    )
    print("  Lowest AUROC:")
    print(
        ensemble.nsmallest(3, "AUROC")[["Disease", "AUROC", "AUPRC_AveragePrecision"]]
        .to_string(index=False, float_format=lambda x: f"{x:.4f}")
    )
    print("\nSaved outputs:")
    for path in [ranking_path, comparison_path, summary_path, prevalence_path]:
        print(f"  {path}")
    print("\nNOTE: AUROC/AUPRC evaluate ranking quality; operating-point metrics evaluate decisions at frozen OOF thresholds.")
    print("AUPRC_AveragePrecision uses sklearn.average_precision_score.")
    print("=" * 76)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        raise
